/**
 * Builds catalogue/ : the reference the agent designs from.
 *
 *   npm run catalogue
 *   npm run catalogue -- --nds-repo <path>     use a local copy of the design system docs instead of git
 *
 * Source of truth is the installed @nice-digital packages (so the catalogue
 * always matches the version designs are built with). "When to use" guidance
 * is added from the design system's docs, read from git via sources.json.
 *
 * catalogue/ is generated. Never edit it by hand.
 */
import fs from "fs";
import path from "path";

const root = path.join(__dirname, "..");
const scope = path.join(root, "node_modules", "@nice-digital");
const out = path.join(root, "catalogue");

// Usage guidance comes from the design system's docs, read from git
// (fetched by `npm run sources -- sync nice-design-system`). --nds-repo <path>
// overrides that with a folder of your choosing.
const repoArg = process.argv.indexOf("--nds-repo");
const ndsRepo =
	repoArg > -1
		? path.resolve(root, process.argv[repoArg + 1])
		: path.join(root, ".sources", "nice-design-system");
const docsDir = path.join(ndsRepo, "docs", "pages", "components");
const hasDocs = fs.existsSync(docsDir);

const read = (file: string) => fs.readFileSync(file, "utf8");
const readJson = (file: string) => JSON.parse(read(file));

// The "when to use" guidance comes from the design system's docs, which are not
// in the published packages. If there is no docs checkout on this machine, keep
// the guidance already in the catalogue rather than silently losing it.
const previousGuidance = new Map<string, string>();
if (!hasDocs && fs.existsSync(path.join(out, "components")))
	for (const file of fs.readdirSync(path.join(out, "components"))) {
		const section = read(path.join(out, "components", file)).match(
			/## Guidance\n\n([\s\S]*?)\n\n## Props \(from the published types\)/
		)?.[1];
		if (section) previousGuidance.set(file.replace(/\.md$/, ""), section);
	}

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, "components"), { recursive: true });

const header =
	"<!-- Generated by `npm run catalogue`. Do not edit. -->\n\n";

// ---------------------------------------------------------------------------
// Components
// ---------------------------------------------------------------------------

/** Plain-text guidance sections from a docs MDX page */
const guidanceFor = (slug: string): string => {
	const file = path.join(docsDir, `${slug}.mdx`);
	if (!hasDocs) return previousGuidance.get(slug) ?? "";
	if (!fs.existsSync(file)) return "";
	const mdx = read(file);

	const description = mdx.match(/description:\s*\n?\s*["'`]([\s\S]*?)["'`],?\s*\n/)?.[1];
	const sections = mdx.split(/^## /m).slice(1);
	const wanted = sections.filter((section) =>
		/^(when to use|when not to use|accessibility|how to use|how it works)/i.test(section)
	);

	const clean = (text: string) =>
		text
			// examples and code blocks are covered by the README section
			.replace(/<Example[\s\S]*?<\/Example>/g, "")
			.replace(/<CH\.[\s\S]*?<\/CH\.[A-Za-z]+>/g, "")
			.replace(/```[\s\S]*?```/g, "")
			.replace(/^(import|export) .*$/gm, "")
			.replace(/\n{3,}/g, "\n\n")
			.trim();

	return [
		description ? clean(description) : "",
		...wanted.map((section) => `### ${clean(section)}`)
	]
		.filter(Boolean)
		.join("\n\n");
};

interface ComponentEntry {
	slug: string;
	pkg: string;
	version: string;
	description: string;
	exports: string[];
}

const components: ComponentEntry[] = [];

for (const dir of fs.readdirSync(scope).filter((name) => name.startsWith("nds-") && name !== "nds-core").sort()) {
	const pkgDir = path.join(scope, dir);
	const pkg = readJson(path.join(pkgDir, "package.json"));
	const slug = dir.replace(/^nds-/, "");
	const esDir = path.join(pkgDir, "es");
	if (!fs.existsSync(esDir)) continue;

	const mainTypes = path.basename(pkg.types ?? pkg.main ?? "").replace(/\.js$/, ".d.ts");
	const typeFiles = fs
		.readdirSync(esDir)
		.filter((file) => file.endsWith(".d.ts") && !file.includes(".test."))
		// entry point first
		.sort((a, b) => Number(b === mainTypes) - Number(a === mainTypes) || a.localeCompare(b));

	const types = typeFiles
		.map((file) =>
			read(path.join(esDir, file))
				.replace(/^import .*$/gm, "")
				.replace(/^export \{\};?$/gm, "")
				.trim()
		)
		.filter(Boolean)
		.join("\n\n");

	const entryTypes = fs.existsSync(path.join(esDir, mainTypes)) ? read(path.join(esDir, mainTypes)) : types;
	const exports = [
		...new Set(
			[
				...entryTypes.matchAll(/export (?:declare )?(?:const|function|class) (\w+)/g),
				...entryTypes.matchAll(/export \{([^}]+)\}/g)
			].flatMap((match) =>
				match[1]
					.split(",")
					.map((name) => name.trim().split(/\s+as\s+/).pop()!.replace(/^type\s+/, ""))
					.filter((name) => /^[A-Z]/.test(name) && !/Props$|Type$/.test(name))
			)
		)
	];

	const guidance = guidanceFor(slug);
	const readme = fs.existsSync(path.join(pkgDir, "README.md"))
		? read(path.join(pkgDir, "README.md"))
				// drop the title and install boilerplate, demote headings under ours
				.replace(/^# .*$/m, "")
				.replace(/^(#{1,5}) /gm, "#$1 ")
				.trim()
		: "";

	components.push({ slug, pkg: pkg.name, version: pkg.version, description: pkg.description ?? "", exports });

	fs.writeFileSync(
		path.join(out, "components", `${slug}.md`),
		`${header}# ${slug}

${pkg.description ?? ""}

- Package: \`${pkg.name}\` ${pkg.version}
- Import: \`import { ${exports.join(", ") || "..."} } from "${pkg.name}";\`
- Styles load automatically with the component. Do not import or override its SCSS.

${guidance ? `## Guidance\n\n${guidance}\n\n` : ""}## Props (from the published types)

Only use props that appear here. Anything else is a type error and fails the checks.

\`\`\`ts
${types}
\`\`\`

${readme ? `## Package README\n\n${readme}\n` : ""}`
	);
}

// ---------------------------------------------------------------------------
// Tokens and helpers (nds-core SCSS)
// ---------------------------------------------------------------------------

const coreScss = path.join(scope, "nds-core", "scss");
const coreVersion = readJson(path.join(scope, "nds-core", "package.json")).version;

const scssFiles = (dir: string): string[] =>
	fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) return entry.name === "vendor" ? [] : scssFiles(full);
		return entry.name.endsWith(".scss") ? [full] : [];
	});

let tokens = `${header}# Tokens and style helpers

From \`@nice-digital/nds-core\` ${coreVersion}. Every colour, space and text size in a sketch
or design must come from here. Raw values (hex colours, px, rem) fail the checks.

\`\`\`scss
@use '@nice-digital/nds-core/scss/colours';
@use '@nice-digital/nds-core/scss/spacing';
@use '@nice-digital/nds-core/scss/typography';
@use '@nice-digital/nds-core/scss/utils';

.example {
  @include typography.font-size(0);
  color: colours.$text;
  padding: utils.rem(spacing.$small spacing.$medium);
}
\`\`\`

`;

const alias = read(path.join(coreScss, "colours", "tokens", "_alias.scss"))
	.replace(/global\.\$/g, "")
	.trim();
tokens += `## Colours: \`colours.$name\`

Use these alias tokens. The value after the colon is the palette colour it maps to, for reference only.
Tokens named after a component (for example \`$tag-...\`) belong to that component: prefer the general ones
(\`$text\`, \`$link\`, \`$border\`, \`$error\`...) in new work.

\`\`\`scss
${alias}
\`\`\`

`;

for (const module of ["spacing", "media-queries", "typography", "layout", "focus", "visibility", "utils", "glyphs"]) {
	const dir = path.join(coreScss, module);
	if (!fs.existsSync(dir)) continue;
	const lines: string[] = [];
	for (const file of scssFiles(dir)) {
		const source = read(file);
		// keep the SassDoc summary line above each public member
		const members = source.matchAll(
			/((?:^\/\/\/ .*\n)*)^(\$[a-z][\w-]*:[^;{]*;|@mixin [a-z][^{]*|@function [a-z][^{]*)/gm
		);
		for (const [, doc, member] of members) {
			const summary = doc.split("\n").find((line) => line.startsWith("/// ") && !line.startsWith("/// @"));
			if (summary) lines.push(summary.replace("///", "//"));
			lines.push(member.trim().replace(/\s+/g, " ").replace(/ !default/, ""));
		}
	}
	if (!lines.length) continue;
	tokens += `## \`${module}\`

\`@use '@nice-digital/nds-core/scss/${module}';\`

\`\`\`scss
${lines.join("\n")}
\`\`\`

`;
}

tokens += `## Utility classes

\`@nice-digital/design-system/scss/base.scss\` is loaded on every page, so the design system's
helper classes are available in markup without writing SCSS, for example \`visually-hidden\`,
\`list list--unstyled\`, and spacing modifiers such as \`mt--0\` and \`mb--e\`.
`;
fs.writeFileSync(path.join(out, "tokens.md"), tokens);

// ---------------------------------------------------------------------------
// Icons
// ---------------------------------------------------------------------------

const iconsLib = path.join(scope, "icons", "lib");
const icons = fs.existsSync(iconsLib)
	? fs
			.readdirSync(iconsLib)
			.filter((file) => file.endsWith(".js") && /^[A-Z]/.test(file))
			.map((file) => file.replace(/\.js$/, ""))
			.sort()
	: [];
fs.writeFileSync(
	path.join(out, "icons.md"),
	`${header}# Icons

From \`@nice-digital/icons\` ${readJson(path.join(scope, "icons", "package.json")).version}. Only these icons exist. Do not draw or import others.

\`\`\`tsx
import ChevronDown from "@nice-digital/icons/lib/ChevronDown";
\`\`\`

${icons.map((icon) => `- ${icon}`).join("\n")}
`
);

// ---------------------------------------------------------------------------
// Index
// ---------------------------------------------------------------------------

const dsVersion = readJson(path.join(scope, "design-system", "package.json")).version;
fs.writeFileSync(
	path.join(out, "index.md"),
	`${header}# NICE Design System catalogue

Built from \`@nice-digital/design-system\` ${dsVersion}${hasDocs ? ", with guidance from the design system docs" : " (no docs checkout was available: usage guidance was carried over from the previous catalogue, or is from package READMEs only)"}.

This is the complete list of what exists. If something is not here, it is not in the design system:
do not invent it inside a design. Sketch it as a new component instead.

| Component | Use it for | Import | Details |
|---|---|---|---|
${components
	.map(
		(c) =>
			`| ${c.slug} | ${c.description.replace(/ (component )?for the NICE Design System/i, "")} | \`${c.exports.join(", ")}\` from \`${c.pkg}\` | [components/${c.slug}.md](components/${c.slug}.md) |`
	)
	.join("\n")}

Also:

- [tokens.md](tokens.md): colours, spacing, text sizes, breakpoints and style helpers
- [icons.md](icons.md): the ${icons.length} icons available

Page chrome (the NICE header and footer) comes from \`@nice-digital/global-nav\` in production and is not part of a design.
`
);

if (!hasDocs)
	console.log(
		previousGuidance.size
			? `Note: the design system docs have not been fetched (npm run sources -- sync nice-design-system), so the "when to use" guidance for ${previousGuidance.size} components was kept from the existing catalogue. It may be out of date for a newer design system version.`
			: 'Note: the design system docs have not been fetched (npm run sources -- sync nice-design-system), so the catalogue has no "when to use" guidance. Fetch them and run this again.'
	);
console.log(
	`Catalogue built: ${components.length} components, ${icons.length} icons${hasDocs ? `, guidance from ${path.relative(root, ndsRepo)}` : ""}`
);
